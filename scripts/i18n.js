export function getLanguage() {
  return localStorage.getItem('spt-language') === 'en' ? 'en' : 'bn';
}

export function setLanguage(language) {
  localStorage.setItem('spt-language', language === 'en' ? 'en' : 'bn');
}

export function t(key, language = getLanguage()) {
  return translations[language]?.[key] || translations.bn[key] || key;
}

export function localDate(value, language = getLanguage(), options = {}) {
  if (!value) return '—';
  const date = value?.toDate ? value.toDate() : new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return date.toLocaleDateString(language === 'bn' ? 'bn-BD' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric', ...options });
}

export function localNumber(value, language = getLanguage(), options = {}) {
  const amount = Number(value ?? 0);
  return amount.toLocaleString(language === 'bn' ? 'bn-BD' : 'en-US', options);
}

